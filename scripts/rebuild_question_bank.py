def red_basic_unit(level: str, number: int) -> int:
    for first, last, unit in RED_BASIC_UNIT_RANGES[level]:
        if first <= number <= last:
            return unit
    raise ValueError(f"unknown basic number {level} {number}")


def red_basic_category(level: str, number: int) -> str:
    """按原图每页右侧的文字/語彙/文法版面分组，不按题号全局猜测。"""
    unit = red_basic_unit(level, number)
    first = next(first for first, _, current in RED_BASIC_UNIT_RANGES[level] if current == unit)
    categories = ("文字", "文字", "語彙", "語彙", "文法", "文法") if unit <= 8 else (
        "文字", "文字", "文字", "語彙", "語彙", "文法", "文法"
    )
    offset = number - first
    while offset >= len(categories):
        offset -= len(categories)
    return categories[offset]


def mock_problem(level: str, kind: str, number: int) -> int:
    for problem, first, last in MOCK_RANGES[(level, kind)]:
        if first <= number <= last:
            return problem
    raise ValueError(f"unknown mock number {level} {kind} {number}")


def reading_start(level: str, kind: str) -> int:
    problem = max(p for p, _, _ in MOCK_RANGES[(level, kind)])
    return next(first for p, first, _ in MOCK_RANGES[(level, kind)] if p == problem)


def blue_material_key(q: dict) -> str:
    return f"{q['part']}:{q['unit']}:{q['dan']}:{q['mondai']}"


def material_key(q: dict, namespace: str) -> str:
    if namespace == "blue":
        return blue_material_key(q)
    return f"{q['level']}:{q['kind']}"


def extract_blue_reading(stem: str) -> str:
    value = normalize_block(stem)
    value = re.sub(r"^(?:text|tex)\s*", "", value, flags=re.I)
    value = re.sub(r"^一つ\s*えらんで\s*ください。\s*", "", value)
    value = re.sub(r"^(?:\d+\s*から\s*\d+|問題\s*\d+).*?ください。\s*", "", value)
    value = re.sub(r"\s*\(第\d+空\)\s*$", "", value)
    return value.strip()


def apply_fix(q: dict, fix: dict) -> None:
    q.update(fix)


def clean_choice(q: dict) -> None:
    q["stem"] = normalize(q["stem"])
    q["stem"] = re.sub(r"\s+---.*$", "", q["stem"])
    instruction = re.compile(r"(?:次の文|つぎの文)の[_＿]+に入る最もよいものを.*?選びなさい。")
    matches = list(instruction.finditer(q["stem"]))
    if matches:
        q["stem"] = q["stem"][matches[-1].end():].strip()
    for item in q["options"]:
        item["text"] = normalize(item["text"])
        item["text"] = re.sub(r"\s+\d+[.．]\s*★.*$", "", item["text"])
        item["text"] = re.sub(r"\s+---.*$", "", item["text"])
    if q.get("answer") and "optionIds" in q["answer"]:
        q["answer"]["optionIds"] = [str(x).lower() for x in q["answer"]["optionIds"]]


def question_subject(namespace: str, q: dict) -> str:
    if namespace == "blue":
        return "reading" if q.get("material") else "grammar"
    return q["subject"]


def clean_fill_blank(stem: str) -> str:
    """统一填空占位符；扫描页下划线经常被 OCR 丢成空格。"""
    stem = re.sub(r"\(\s*\)|（\s*）", "（＿＿＿）", stem)
    return re.sub(r"_+|＿+", "＿＿＿", stem)


def prepare_blue() -> list[dict]:
    questions = json.loads(BLUE_INPUT.read_text(encoding="utf-8"))
    readings: dict[str, dict[str, str]] = {}
    for q in questions:
        if q["dan"] == 2 and q["mondai"] == 3:
            key = blue_material_key(q)
            readings[key] = {
                "title": f"{q['part'].upper()}·第{q['unit']}单元·实战训练·問題3阅读短文",
                "content": BLUE_READING_CONTENT.get((q["part"], q["unit"]), extract_blue_reading(q["stem"])),
            }
    for q in questions:
        apply_fix(q, BLUE_FIXES.get(key_blue(q), {}))
        if q["dan"] == 2 or (q["part"] == "n4" and q["dan"] == 1 and q["mondai"] == 1):
            q["type"] = "single_choice"
        q["category"] = f"{q['part'].upper()}·第{q['unit']}单元·{'基础练习' if q['dan'] == 1 else '实战训练'}·問題{q['mondai']}"
        if q["dan"] == 2 and q["mondai"] == 3:
            q["material"] = readings[blue_material_key(q)]
            q["stem"] = f"阅读短文（第{q['no']}空）"
        q["subject"] = question_subject("blue", q)
        if q["type"] == "single_choice":
            official_answer = BLUE_OFFICIAL_ANSWERS.get(key_blue(q))
            if official_answer:
                q["answer"] = {"optionIds": [official_answer]}
            clean_choice(q)
        else:
            q["stem"] = normalize_block(q["stem"]) if "|" in q["stem"] else normalize(q["stem"])
            q["stem"] = re.sub(r"^\d{1,2}\s+", "", q["stem"])
            if q["type"] == "fill_blank":
                q["stem"] = clean_fill_blank(q["stem"])
    return questions


def prepare_red() -> list[dict]:
    questions = json.loads(RED_INPUT.read_text(encoding="utf-8"))
    for q in questions:
        apply_fix(q, RED_FIXES.get(key_red(q), {}))
        apply_fix(q, RED_FINAL_FIXES.get(key_red(q), {}))
        if q["kind"] == "basic":
            q["unit"] = red_basic_unit(q["level"], q["number"])
        if q["kind"] == "basic":
            category = red_basic_category(q["level"], q["number"])
            q["category"] = f"{q['level'].upper()}·Unit {q['unit']}·{category}"
        else:
            q["category"] = f"{q['level'].upper()}·模拟测试第{1 if q['kind'] == 'mock1' else 2}回·問題{mock_problem(q['level'], q['kind'], q['number'])}"
        if q["kind"].startswith("mock") and q["number"] >= reading_start(q["level"], q["kind"]):
            q["material"] = READING[(q["level"], q["kind"])]
            q["subject"] = "reading"
            q["stem"] = f"【第{q['number']:03d}题】第{q['number']}空"
        clean_choice(q)
        q["stem"] = re.sub(r"^【第\s*\d{1,4}题】\s*", "", q["stem"])
        # 解析页 OCR 的解释混入相邻题目，未经人工复核不进入学习者结果页。
        q["explanation"] = ""
        for index, option in enumerate(q["options"], 1):
            option["label"] = str(index)
    return questions


def validate(blue: list[dict], red: list[dict]) -> None:
    errors: list[str] = []
    review = json.loads(MANUAL_REVIEW.read_text(encoding="utf-8"))
    samples = json.loads(SOURCE_SECTION_SAMPLES.read_text(encoding="utf-8"))
    mapping = json.loads(KNOWLEDGE_MAPPING_INPUT.read_text(encoding="utf-8"))
    points = json.loads(KNOWLEDGE_POINTS_INPUT.read_text(encoding="utf-8"))["points"]
    point_by_id = {point["id"]: point for point in points}
    mapping_keys = {(item["source"], tuple(item["key"])) for item in mapping["questions"]}
    mapping_by_key = {(item["source"], tuple(item["key"])): item for item in mapping["questions"]}
    pending_sections = set()
    for item in samples.get("items", []):
        required = ("book", "key", "sourceSection", "status", "checks")
        if any(not item.get(field) and field != "key" for field in required) or item.get("status") != "pending":
            errors.append(f"invalid pending source sample: {item}")
        elif len(item.get("checks", [])) < 5:
            errors.append(f"incomplete pending source sample: {item}")
        pending_sections.add((item.get("book"), item.get("sourceSection")))
    for item in review:
        if item.get("status") == "sampled":
            errors.append(f"manual review contains unverified sample: {item}")
        if item.get("status") == "source_verified":
            required = ("book", "key", "sourceSection", "page", "reviewMethod", "reviewedAt", "checks", "note")
            if any(not item.get(field) and field != "key" for field in required) or len(item.get("checks", [])) < 5:
                errors.append(f"incomplete source verification: {item}")
    reviewed_duplicates = {
        (item["book"], tuple(item["key"]))
        for item in review
        if item.get("status") == "source_verified"
    }
    if len(blue) != 986:
        errors.append(f"blue count={len(blue)} expected=986")
    if len(red) != 1000:
        errors.append(f"redblue count={len(red)} expected=1000")
    for book, questions in (("blue", blue), ("redblue", red)):
        seen: set[tuple] = set()
        groups: dict[tuple, list[int]] = {}
        for q in questions:
            key = key_blue(q) if book == "blue" else key_red(q)
            if key in seen:
                errors.append(f"duplicate {book} {key}")
            seen.add(key)
            group_key = (q["part"], q["unit"], q["dan"], q["mondai"]) if book == "blue" else (q["level"], q["kind"])
            groups.setdefault(group_key, []).append(q["no"] if book == "blue" else q["number"])
            if not q.get("category"):
                errors.append(f"missing category {book} {key}")
            if (book, key) not in mapping_keys:
                errors.append(f"missing knowledge mapping {book} {key}")
            mapping_item = mapping_by_key.get((book, key))
            if mapping_item is None or mapping_item.get("reviewStatus") != "not_required":
                errors.append(f"formal mapping is not confirmed {book} {key}")
            elif not mapping_item.get("knowledgePointIds"):
                errors.append(f"formal mapping has no root {book} {key}")
            else:
                formal_ids = set(mapping_item["knowledgePointIds"])
                suggested_ids = set(mapping_item.get("suggestedKnowledgePointIds", []))
                if formal_ids & suggested_ids or (suggested_ids and mapping_item.get("suggestedReviewStatus") != "pending"):
                    errors.append(f"pending suggestion entered formal mapping {book} {key}")
                for point_id in mapping_item["knowledgePointIds"] + list(suggested_ids):
                    point = point_by_id.get(point_id)
                    if point is None or point.get("status") != "published":
                        errors.append(f"mapping uses unknown or unpublished knowledge point {book} {key} {point_id}")
                    elif point.get("level") != (q["part"] if book == "blue" else q["level"]) or point.get("subject") != q.get("subject"):
                        errors.append(f"mapping scope mismatch {book} {key} {point_id}")
            if not q.get("stem", "").strip():
                errors.append(f"missing stem {book} {key}")
            if not q.get("answer"):
                errors.append(f"missing answer {book} {key}")
            if book == "blue" and key == ("n5", 2, 1, 2, 0):
                for row in ("立つ", "行く", "飛ぶ", "生かす", "知る", "切る", "食べる", "寝る", "来る", "する", "運動する"):
                    if row not in q.get("stem", ""):
                        errors.append(f"incomplete table {book} {key}: missing {row}")
            if q["type"] == "single_choice":
                if len(q.get("options", [])) != 4:
                    errors.append(f"options {book} {key}={len(q.get('options', []))}")
                option_ids = [option.get("id") for option in q.get("options", [])]
                if option_ids != ["a", "b", "c", "d"]:
                    errors.append(f"option ids {book} {key}={option_ids}")
                if len({option.get("text") for option in q.get("options", [])}) != len(q.get("options", [])):
                    if (book, key) not in reviewed_duplicates:
                        errors.append(f"duplicate options {book} {key}")
                if any(not option.get("text", "").strip() for option in q.get("options", [])):
                    errors.append(f"empty option {book} {key}")
                answer = q.get("answer", {}).get("optionIds", []) if q.get("answer") else []
                valid_answer_ids = {"a", "b", "c", "d"}
                if len(answer) != 1 or answer[0] not in valid_answer_ids:
                    errors.append(f"answer {book} {key}={answer}")
            elif q["type"] in {"fill_blank", "short_answer"}:
                answer = q.get("answer") or {}
                if not answer.get("acceptable") and not answer.get("reference"):
                    errors.append(f"answer shape {book} {key}={answer}")
                if q["type"] == "fill_blank" and not re.search(r"\(\s*\)|（\s*）|_+|＿+", q["stem"]):
                    errors.append(f"missing blank marker {book} {key}")
            text = " ".join([q.get("stem", "")] + [o.get("text", "") for o in q.get("options", [])])
            if NOISE.search(text):
                errors.append(f"noise {book} {key}")
            if OCR_SUSPECT.search(text):
                errors.append(f"ocr suspect {book} {key}")
            if QUESTION_NUMBER_RESIDUE.search(q.get("stem", "")):
                errors.append(f"question number residue {book} {key}")
            if ("material" in q) != (q.get("subject") == "reading"):
                errors.append(f"material relation {book} {key}")
            if not q.get("category") or (book, q["category"]) not in pending_sections:
                errors.append(f"missing pending source section {book} {q.get('category')}")
        for group, numbers in groups.items():
            expected = set(range(min(numbers), max(numbers) + 1))
            if set(numbers) != expected:
                errors.append(f"non-contiguous {book} {group}: {sorted(set(numbers) ^ expected)}")
    for group, ranges in MOCK_RANGES.items():
        level, kind = group
        expected = {n for _, first, last in ranges for n in range(first, last + 1)}
        actual = {q["number"] for q in red if q["level"] == level and q["kind"] == kind}
        if actual != expected:
            errors.append(f"mock range {group}: expected {len(expected)}, got {len(actual)}")
        start = reading_start(level, kind)
        reading = [q for q in red if q["level"] == level and q["kind"] == kind and q["number"] >= start]
        if len(reading) != 5 or any("material" not in q for q in reading):
            errors.append(f"reading material {group}: {len(reading)} records")
    if errors:
        raise ValueError("\n".join(errors[:40]))


def stable_uuid(namespace: str, name: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"https://aishuati.local/{namespace}/{name}"))


def sql_quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def source_order_key(namespace: str, q: dict) -> tuple:
    if namespace == "blue":
        return ({"n5": 0, "n4": 1}[q["part"]], q["unit"], q["dan"], q["mondai"], q["no"])
    return ({"n5": 0, "n4": 1}[q["level"]], {"basic": 0, "mock1": 1, "mock2": 2}[q["kind"]], q["number"])


