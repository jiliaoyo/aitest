def normalize(value: str) -> str:
    value = unicodedata.normalize("NFKC", str(value)).replace("\r", " ")
    value = value.replace("**", "").replace("###", "")
    value = re.sub(r"\s+", " ", value).strip()
    value = re.sub(r"(?:^|\s)(?:attsu?|osem|text|image)(?=\s|$)", " ", value, flags=re.I)
    value = re.sub(r"\s+(?:attsu|osem)[a-z0-9]*.*$", "", value, flags=re.I)
    value = re.sub(r"(?:Unit\s*\d+|第\s*\d+\s*(?:单元|単元|回)).*$", "", value, flags=re.I)
    value = re.sub(r"\s+角和.*$", "", value)
    value = re.sub(r"\s+(?:もんだい|問題)\s*[1-9０-９].*$", "", value, flags=re.I)
    value = re.sub(r"\s+(?:attsu?|osem|text|image)\b.*$", "", value, flags=re.I)
    value = re.sub(r"\s+第\s*\d+\s*回.*$", "", value)
    # 题目页/解析页相邻时，OCR 会把下一段页眉或说明拼到当前字段。
    value = re.sub(r"\s+(?:---\s*)?(?:文字\s+語彙\s+文法|rs|qk|hydraulic\s+press)\b.*$", "", value, flags=re.I)
    value = re.sub(r"\s+(?:---\s*)?unit(?:\s*\(?\d+\)?)?\b.*$", "", value, flags=re.I)
    value = re.sub(r"\s+(?:---\s*)?問題\b.*$", "", value, flags=re.I)
    value = re.sub(r"\s+\d+\s+の\s+ぶんと\b.*$", "", value, flags=re.I)
    value = re.sub(r"\s+争:\*.*$", "", value)
    value = re.sub(r"\s+第(?:\s|$).*", "", value)
    value = re.sub(r"\s+\d+\s+回$", "", value)
    value = re.sub(r"\s+〇(?:\s+〇)*.*$", "", value)
    value = re.sub(r"^[I|l]\s+", "", value)
    return value.strip(" |-*#、")


def normalize_block(value: str) -> str:
	"""保留表格题的换行，同时清理每行多余空格。"""
	value = unicodedata.normalize("NFKC", str(value)).replace("\r", "")
	lines = [re.sub(r"[ \t]+", " ", line).strip() for line in value.split("\n")]
	return "\n".join(line for line in lines if line).strip()


