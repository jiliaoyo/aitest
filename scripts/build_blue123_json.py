ALLOWED_ITEM_KEYS = {
    "rawExcerpt", "materialKey", "type", "stem", "options", "materialTitle",
    "materialContent", "levelCode", "subjectCode", "difficulty",
    "knowledgePointNames", "sourceAnswer", "aiSuggestedAnswer", "anomalies",
}


def validate_items(items: list[dict], level: str, unit: int) -> None:
    errors = []
    for number, q in enumerate(items, 1):
        prefix = f"{level}/u{unit:02d} item {number}"
        unknown = set(q) - ALLOWED_ITEM_KEYS
        if unknown:
            errors.append(f"{prefix}: unknown keys {sorted(unknown)}")
        if q.get("levelCode") != level.lower() or q.get("subjectCode") != "grammar":
            errors.append(f"{prefix}: wrong classification")
        if q.get("type") not in {"single_choice", "multiple_choice", "fill_blank", "short_answer"}:
            errors.append(f"{prefix}: invalid type")
        if len(str(q.get("stem") or "").strip()) < 2:
            errors.append(f"{prefix}: empty stem")
        options = q.get("options") or []
        if q.get("type") in {"single_choice", "multiple_choice"}:
            if len(options) < 4:
                errors.append(f"{prefix}: choice has {len(options)} options")
            ids = [o.get("id") for o in options]
            if len(ids) != len(set(ids)) or any(not x for x in ids):
                errors.append(f"{prefix}: invalid option ids")
            if any(not str(o.get("text") or "").strip() for o in options):
                errors.append(f"{prefix}: empty option")
        answer = q.get("sourceAnswer")
        if not isinstance(answer, dict) or answer.get("authority") != "official":
            errors.append(f"{prefix}: missing official answer")
        else:
            value = answer.get("value") or {}
            if q.get("type") in {"single_choice", "multiple_choice"}:
                ids = value.get("optionIds") or []
                valid_ids = {o.get("id") for o in options}
                if not ids or any(i not in valid_ids for i in ids):
                    errors.append(f"{prefix}: answer does not reference options")
                if q.get("type") == "single_choice" and len(ids) != 1:
                    errors.append(f"{prefix}: single choice has multiple answers")
            elif q.get("type") == "fill_blank" and not value.get("acceptable"):
                errors.append(f"{prefix}: empty acceptable answers")
            elif q.get("type") == "short_answer" and not value.get("reference"):
                errors.append(f"{prefix}: empty reference answer")
        if not 1 <= q.get("difficulty", 0) <= 5:
            errors.append(f"{prefix}: invalid difficulty")
    if errors:
        raise ValueError("\n".join(errors))


