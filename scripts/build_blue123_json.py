def item(stem: str, qtype: str, options=None, answer=None, *, raw=None,
         title="", content="", anomalies=None):
    options = options or []
    result = {
        "rawExcerpt": (raw or stem).strip()[:5000],
        "materialKey": "",
        "type": qtype,
        "stem": stem.strip(),
        "options": [
            {"id": chr(97 + i), "label": chr(65 + i), "text": text.strip()}
            for i, text in enumerate(options)
        ],
        "materialTitle": title,
        "materialContent": content,
        "levelCode": "n3",
        "subjectCode": "grammar",
        "difficulty": 3,
        "knowledgePointNames": [],
        "sourceAnswer": None,
        "aiSuggestedAnswer": None,
        "anomalies": list(anomalies or []),
    }
    if answer is not None:
        if qtype in {"single_choice", "multiple_choice"}:
            ids = answer if isinstance(answer, list) else [answer]
            result["sourceAnswer"] = {
                "value": {"optionIds": [chr(96 + n) for n in ids]},
                "authority": "official",
                "explanation": "",
            }
        else:
            values = answer if isinstance(answer, list) else [answer]
            result["sourceAnswer"] = {
                "value": {"acceptable": values},
                "authority": "official",
                "explanation": "",
            }
    return result


def choices(stem: str, options: list[str], answer: int, **kwargs):
    return item(stem, "single_choice", options, answer, **kwargs)


def shared(stem: str, options: list[str], answer: str, **kwargs):
    return item(stem, "single_choice", options, ord(answer.upper()) - 64, **kwargs)


def fill(stem: str, answer: str | list[str], **kwargs):
    return item(stem, "fill_blank", answer=answer, **kwargs)


def short(stem: str, reference: str):
    result = item(stem, "short_answer")
    result["sourceAnswer"] = {
        "value": {"reference": reference},
        "authority": "official",
        "explanation": "",
    }
    return result


def reading(unit: int, content: str, number: int, options: list[str], answer: int):
    return choices(
        f"文章中の（{number}）に入る最もよいものを選びなさい。",
        options,
        answer,
        title=f"第{unit}単元 パートⅡ 問題3",
        content=content,
    )


def sort_question(stem: str, tokens: list[str], star_answer: int):
    return choices(stem, tokens, star_answer)


def normalize_existing(raw: dict, level: str) -> dict:
    """Remove extraction-only noise while retaining source anomalies."""
    q = copy.deepcopy(raw)
    q["levelCode"] = level.lower()
    q["subjectCode"] = "grammar"
    q["materialKey"] = str(q.get("materialKey") or "")
    q["materialTitle"] = str(q.get("materialTitle") or "")
    q["materialContent"] = str(q.get("materialContent") or "")
    q["stem"] = re.sub(r"[ \t]+", " ", str(q.get("stem") or "")).strip()
    q["rawExcerpt"] = str(q.get("rawExcerpt") or q["stem"]).strip()[:5000]
    q["knowledgePointNames"] = list(q.get("knowledgePointNames") or [])
    q["aiSuggestedAnswer"] = q.get("aiSuggestedAnswer")
    q["anomalies"] = list(q.get("anomalies") or [])
    options = []
    for i, option in enumerate(q.get("options") or []):
        text = re.sub(r"[ \t]+", " ", str(option.get("text") or "")).strip()
        if not text:
            continue
        options.append({
            "id": chr(97 + i),
            "label": chr(65 + i),
            "text": text,
        })
    q["options"] = options
    answer = q.get("sourceAnswer")
    if isinstance(answer, dict):
        value = answer.get("value") or {}
        if "optionIds" in value:
            value = {"optionIds": [str(x).lower() for x in value["optionIds"]]}
        elif "acceptable" in value:
            value = {"acceptable": [str(x).strip() for x in value["acceptable"] if str(x).strip()]}
        q["sourceAnswer"] = {
            "value": value,
            "authority": "official",
            "explanation": str(answer.get("explanation") or ""),
        }
    elif answer is not None:
        q["sourceAnswer"] = None
    return q


